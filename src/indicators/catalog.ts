export function createIndicatorInstance(
  type: IndicatorId,
  existingPaneCount: number
): IndicatorConfig {
  const def = INDICATOR_CATALOG.find((d) => d.type === type)!;
  const isOwnPane = def.category === 'oscillator' || def.type === 'VOL_MA' || def.type === 'VOL';
  return {
    id: `${type}_${Date.now()}_${Math.random().toString(36).slice(2, 6)}`,
    type: def.type,
    name: def.shortName,
    category: def.category,
    paneIndex: isOwnPane ? existingPaneCount : 0,
    visible: true,
    source: def.defaultSource,
    params: { ...def.defaultParams },
    colors: { ...def.defaultColors },
    lineWidth: 2,
    timeframeVisibility: 'all',
  };
}
